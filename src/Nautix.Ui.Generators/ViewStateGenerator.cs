using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Nautix.Ui.Generators;

/// <summary>
/// Generates a read-only <c>INotifyPropertyChanged</c> projection of a state record for a class marked with
/// <c>[GenerateViewState(typeof(TState))]</c>. The projection subscribes to a <c>Store&lt;TState&gt;</c>.
/// </summary>
[Generator]
public sealed class ViewStateGenerator : IIncrementalGenerator
{
    public const string AttributeMetadataName = "Nautix.Ui.Mvu.GenerateViewStateAttribute";

    private static readonly DiagnosticDescriptor _mustBePartial = new(
        "NXVS001",
        "View state class must be partial",
        "'{0}' is marked with [GenerateViewState] and must be a partial, non-nested class",
        "Nautix.Ui",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor _invalidState = new(
        "NXVS002",
        "Invalid state type",
        "[GenerateViewState] on '{0}' needs a typeof(...) argument naming a class or record",
        "Nautix.Ui",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var targets = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeMetadataName,
            static (node, _) => node is ClassDeclarationSyntax,
            static (ctx, _) => Model.Create(ctx));

        context.RegisterSourceOutput(targets, static (spc, model) =>
        {
            if (model is null)
            {
                return;
            }

            foreach (var diagnostic in model.Diagnostics)
            {
                spc.ReportDiagnostic(diagnostic);
            }

            if (model.Source is not null)
            {
                spc.AddSource(model.HintName, model.Source);
            }
        });
    }

    private sealed class Model
    {
        private Model(string hintName, string? source, ImmutableArray<Diagnostic> diagnostics)
        {
            HintName = hintName;
            Source = source;
            Diagnostics = diagnostics;
        }

        public string HintName { get; }

        public string? Source { get; }

        public ImmutableArray<Diagnostic> Diagnostics { get; }

        public static Model? Create(GeneratorAttributeSyntaxContext ctx)
        {
            if (ctx.TargetSymbol is not INamedTypeSymbol target)
            {
                return null;
            }

            var location = ctx.TargetNode.GetLocation();
            var hint = target.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                .Replace("global::", string.Empty).Replace('<', '_').Replace('>', '_') + ".ViewState.g.cs";

            var isPartial = ctx.TargetNode is ClassDeclarationSyntax cds
                && cds.Modifiers.Any(m => m.Text == "partial");
            if (!isPartial || target.ContainingType is not null)
            {
                return new Model(hint, null, ImmutableArray.Create(Diagnostic.Create(_mustBePartial, location, target.Name)));
            }

            var argument = ctx.Attributes[0].ConstructorArguments;
            if (argument.Length != 1 || argument[0].Value is not INamedTypeSymbol state
                || state.TypeKind is not (TypeKind.Class))
            {
                return new Model(hint, null, ImmutableArray.Create(Diagnostic.Create(_invalidState, location, target.Name)));
            }

            return new Model(hint, Emit(target, state), ImmutableArray<Diagnostic>.Empty);
        }

        private static string Emit(INamedTypeSymbol target, INamedTypeSymbol state)
        {
            var stateType = state.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var properties = state.GetMembers()
                .OfType<IPropertySymbol>()
                .Where(p => p.DeclaredAccessibility == Accessibility.Public
                    && !p.IsStatic && !p.IsIndexer && p.GetMethod is not null
                    && p.Name != "CurrentState")
                .ToImmutableArray();

            var typeFormat = SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(
                SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            if (!target.ContainingNamespace.IsGlobalNamespace)
            {
                sb.Append("namespace ").Append(target.ContainingNamespace.ToDisplayString()).AppendLine(";").AppendLine();
            }

            sb.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"Nautix.Ui.Generators\", \"1.0\")]");
            sb.Append(AccessibilityKeyword(target.DeclaredAccessibility)).Append(" sealed partial class ").Append(target.Name)
                .AppendLine(" : global::System.ComponentModel.INotifyPropertyChanged, global::System.IDisposable");
            sb.AppendLine("{");
            sb.AppendLine("    private readonly global::System.IDisposable _subscription;");
            sb.Append("    private ").Append(stateType).AppendLine(" _state;");
            sb.AppendLine();
            sb.Append("    public ").Append(target.Name).Append("(global::Nautix.Ui.Mvu.Store<").Append(stateType).AppendLine("> store)");
            sb.AppendLine("    {");
            sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(store);");
            sb.AppendLine("        _state = store.Current;");
            sb.Append("        _subscription = store.Subscribe(global::Nautix.Ui.Mvu.DelegateObserver.Create<").Append(stateType).AppendLine(">(Apply));");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    public event global::System.ComponentModel.PropertyChangedEventHandler? PropertyChanged;");
            sb.AppendLine();
            sb.Append("    public ").Append(stateType).AppendLine(" CurrentState => _state;");
            foreach (var property in properties)
            {
                sb.Append("    public ").Append(property.Type.ToDisplayString(typeFormat)).Append(' ').Append(property.Name)
                    .Append(" => _state.").Append(property.Name).AppendLine(";");
            }

            sb.AppendLine();
            sb.AppendLine("    public void Dispose() => _subscription.Dispose();");
            sb.AppendLine();
            sb.Append("    private void Apply(").Append(stateType).AppendLine(" next)");
            sb.AppendLine("    {");
            sb.AppendLine("        var previous = _state;");
            sb.AppendLine("        _state = next;");
            foreach (var property in properties)
            {
                sb.Append("        if (!global::System.Collections.Generic.EqualityComparer<").Append(property.Type.ToDisplayString(typeFormat))
                    .Append(">.Default.Equals(previous.").Append(property.Name).Append(", next.").Append(property.Name).AppendLine("))");
                sb.AppendLine("        {");
                sb.Append("            PropertyChanged?.Invoke(this, new global::System.ComponentModel.PropertyChangedEventArgs(\"")
                    .Append(property.Name).AppendLine("\"));");
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            sb.AppendLine("        PropertyChanged?.Invoke(this, new global::System.ComponentModel.PropertyChangedEventArgs(\"CurrentState\"));");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string AccessibilityKeyword(Accessibility accessibility) =>
            accessibility == Accessibility.Public ? "public" : "internal";
    }
}
